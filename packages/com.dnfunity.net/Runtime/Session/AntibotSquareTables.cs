        /// <summary>逆 S 盒（由 S 盒求逆得到）。</summary>
        internal static readonly byte[] InvSBox = BuildInverse(SBox);

        /// <summary>θ 表：Theta[x] = x·(02 01 01 03)，四个字节低位在前。密钥调度里整字做 θ 时用它。</summary>
        internal static readonly uint[] Theta = BuildTheta();

        /// <summary>加密每轮的合并查表。Encrypt[0][x] = Theta[S[x]]，Encrypt[1..3] 是它循环左移 8/16/24 位。</summary>
        internal static readonly uint[][] Encrypt = BuildRoundTables(true);

        /// <summary>解密每轮的合并查表。Decrypt[0][x] = x' · (0E 09 0D 0B)（x' 为逆 S 盒输出），Decrypt[1..3] 同样依次循环左移。</summary>
        internal static readonly uint[][] Decrypt = BuildRoundTables(false);

        private static byte[] BuildInverse(byte[] box)
        {
            byte[] inverse = new byte[256];
            for (int x = 0; x < 256; x++)
            {
                inverse[box[x]] = (byte)x;
            }

            return inverse;
        }

        private static uint[] BuildTheta()
        {
            uint[] table = new uint[256];
            for (int x = 0; x < 256; x++)
            {
                table[x] = ForwardColumn(x);
            }

            return table;
        }

        private static uint[][] BuildRoundTables(bool forward)
        {
            uint[][] tables = { new uint[256], new uint[256], new uint[256], new uint[256] };
            for (int x = 0; x < 256; x++)
            {
                uint word = forward ? ForwardColumn(SBox[x]) : InverseColumn(InvSBox[x]);
                for (int i = 0; i < 4; i++)
                {
                    int shift = 8 * i;
                    tables[i][x] = shift == 0 ? word : (word << shift) | (word >> (32 - shift));
                }
            }

            return tables;
        }

        /// <summary>v·(02 01 01 03) 打包成小端字。</summary>
        private static uint ForwardColumn(int v)
        {
            return (uint)Multiply(v, 0x02) | ((uint)v << 8) | ((uint)v << 16) | ((uint)Multiply(v, 0x03) << 24);
        }

        /// <summary>v·(0E 09 0D 0B) 打包成小端字（θ 的逆）。</summary>
        private static uint InverseColumn(int v)
        {
            return (uint)Multiply(v, 0x0E) | ((uint)Multiply(v, 0x09) << 8) | ((uint)Multiply(v, 0x0D) << 16) | ((uint)Multiply(v, 0x0B) << 24);
        }

        /// <summary>GF(2^8) 乘法，域多项式 0x1F5。</summary>
        private static byte Multiply(int a, int b)
        {
            int product = 0;
            while (b != 0)
            {
                if ((b & 1) != 0)
                {
                    product ^= a;
                }

                a <<= 1;
                if ((a & 0x100) != 0)
                {
                    a ^= 0x1F5;
                }

                b >>= 1;
            }

            return (byte)product;
        }
